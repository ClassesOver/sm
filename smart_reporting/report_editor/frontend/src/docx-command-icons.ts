export function fillDocxCommandIcons(root: HTMLElement): void {
  for (const button of root.querySelectorAll<HTMLButtonElement>('.docx-ribbon-command')) {
    if (button.querySelector('svg')) continue
    const label = button.textContent?.trim() ?? '', action = button.dataset.action ?? ''
    const icon = labels[label] ?? actions[action] ?? (action.startsWith('table-autofit-') ? IconAutoFit : action.startsWith('table-align-top') ? IconCellAlignTop : action.startsWith('table-align-middle') ? IconCellAlignMiddle : action.startsWith('table-align-bottom') ? IconCellAlignBottom : undefined)
    if (icon) button.insertAdjacentHTML('afterbegin',renderToStaticMarkup(createElement(icon,{size:16})))
  }
}
