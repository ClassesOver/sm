import assert from 'node:assert/strict'
import { join } from 'node:path'

// 由主 smoke 的 --viewport-only 分支运行；来源为其真实保存引擎产出的 revision-2.xlsx。
export async function runPivotControlViewportSmoke({ page, base, ready, command, goto, draft, evidence }) {
  await page.goto(`${base}/reports/v1/native/pivot-protection/1`); await ready(); await goto('Pivot!A1')
  const slicer = page.locator('[data-pivot-control="Slicer_P1_F1"]'), timeline = page.locator('[data-pivot-control="Timeline_P1_F0"]'), delivery = page.locator('[data-pivot-control="Timeline_P1_F4"]')
  await slicer.waitFor({ state: 'visible' })
  const bounds = async () => ({ slicer: await slicer.boundingBox(), timeline: await timeline.boundingBox() })
  const separation = value => value.slicer.x - value.timeline.x
  const initial = await bounds()
  await goto('Pivot!B3'); await command('View', 'freeze-panes')
  const crossingStart = await delivery.boundingBox()
  await page.mouse.move(350, 750); await page.mouse.wheel(0, 260)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 100, crossingStart.y)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); let parent = button.parentElement; while (parent && !parent.classList.contains('univer-z-10')) parent = parent.parentElement; const clip = parent?.getBoundingClientRect(); return clip && clip.bottom >= r.bottom && clip.right >= r.right }), '跨冻结分隔线的切片器应用按钮被裁切')
  // 时间线滚过切片器时按普通绘图层顺序遮盖；滚离后再验证真实点击命中。
  await page.mouse.wheel(0, 340)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 550, crossingStart.y)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), '跨冻结分隔线控件滚动后不可点击')
  await page.screenshot({ path: join(evidence, 'crossing-frozen-controls.png'), fullPage: true })
  await page.mouse.wheel(0, -600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top >= top - 2, crossingStart.y)
  await goto('Pivot!B3'); await command('View', 'freeze-panes')
  await goto('Pivot!K3'); await command('View', 'freeze-panes')
  await page.locator('[data-ribbon-menu="zoom"]').selectOption('125')
  await page.waitForFunction(() => document.querySelector('[data-pivot-control="Slicer_P1_F1"]')?.getBoundingClientRect().width > 220)
  const crossed = await bounds(), crossedDelivery = await delivery.boundingBox()
  await page.mouse.move(1450, 600); await page.mouse.wheel(160, 600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 550, crossedDelivery.y)
  const crossedScrolled = await bounds()
  assert(Math.abs(crossedScrolled.slicer.x - crossed.slicer.x) < 2 && Math.abs(crossedScrolled.slicer.y - crossed.slicer.y) < 2, `跨双向冻结线的控件随滚动漂移：${JSON.stringify({ crossed, crossedScrolled })}`)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), '跨双向冻结线控件不可点击')
  await page.screenshot({ path: join(evidence, 'crossing-both-dividers.png'), fullPage: true })
  await page.mouse.wheel(-600, -600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top >= top - 2, crossedDelivery.y)
  await command('View', 'zoom-reset')
  await page.waitForFunction(() => document.querySelector('[data-pivot-control="Slicer_P1_F1"]')?.getBoundingClientRect().width < 200)
  await goto('Pivot!K3'); await command('View', 'freeze-panes')
  await goto('Pivot!B15'); await command('View', 'freeze-panes')
  const frozen = await bounds()
  const deliveryStart = await delivery.boundingBox()
  await page.mouse.move(350, 750); await page.mouse.wheel(0, 160)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 20, deliveryStart.y)
  const scrolled = await bounds()
  assert(Math.abs(scrolled.slicer.y - frozen.slicer.y) < 2, `冻结行中的切片器发生纵向漂移：${JSON.stringify({ frozen, scrolled })}`)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), '冻结带内切片器的应用按钮不可点击')
  await page.screenshot({ path: join(evidence, 'frozen-controls.png'), fullPage: true })
  await page.mouse.wheel(0, -600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top >= top - 2, deliveryStart.y)
  await goto('Pivot!B15'); await command('View', 'freeze-panes')
  await slicer.getByLabel('West', { exact: true }).check()
  await timeline.getByLabel('结束日期', { exact: true }).fill('2026-01-15')
  await command('View', 'toggle-right-to-left')
  await page.waitForFunction(() => document.querySelector('.workbook-feedback')?.textContent?.includes('已切换为从右到左'))
  await slicer.waitFor({ state: 'visible' })
  assert(await slicer.getByLabel('West', { exact: true }).isChecked(), 'RTL 切换丢失未应用成员勾选')
  assert.equal(await timeline.getByLabel('结束日期', { exact: true }).inputValue(), '2026-01-15', 'RTL 切换丢失未应用日期区间')
  const rtl = await bounds()
  await page.screenshot({ path: join(evidence, 'rtl-controls.png'), fullPage: true })
  await goto('Data!A1'); await goto('Pivot!A1'); await slicer.waitFor({ state: 'visible' })
  const reattached = await bounds()
  // 定位可能滚动整个视口；比较两控件的锚点间距，避免把一致的视口平移误判成控件漂移。
  assert(Math.abs(separation(rtl) - separation(reattached)) < 2, `RTL 切换和重新挂载锚点间距不一致：${JSON.stringify({ rtl, reattached })}`)
  assert(separation(rtl) * separation(initial) < 0, 'RTL 未镜像控件间的单元格锚点方向')
  await slicer.getByLabel('West', { exact: true }).uncheck()
  await timeline.getByLabel('结束日期', { exact: true }).fill('2026-01-31')
  const count = (await draft()).filter(op => op.kind === 'upsertPivotControl').length
  await slicer.locator('[type="submit"]').click()
  await page.waitForFunction(count => Object.keys(localStorage).filter(key => key.startsWith('native-editor-draft:')).some(key => (JSON.parse(localStorage.getItem(key)).operations ?? []).filter(op => op.kind === 'upsertPivotControl').length > count), count)
  await page.waitForFunction(() => !document.querySelector('#report-editor')?.inert)
  await slicer.waitFor({ state: 'visible' })
  const applied = await bounds()
  assert(Math.abs(separation(applied) - separation(reattached)) < 2, 'RTL 筛选后控件锚点间距发生变化')
  await goto('Pivot!K3'); await command('View', 'freeze-panes')
  const rtlColumns = await bounds(), rtlColumnsDelivery = await delivery.boundingBox()
  await page.mouse.move(350, 750); await page.mouse.wheel(-160, 600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 550, rtlColumnsDelivery.y)
  const rtlColumnsScrolled = await bounds()
  assert(Math.abs(rtlColumnsScrolled.slicer.x - rtlColumns.slicer.x) < 2 && Math.abs(rtlColumnsScrolled.slicer.y - rtlColumns.slicer.y) < 2, `RTL 冻结列锚点漂移：${JSON.stringify({ rtlColumns, rtlColumnsScrolled })}`)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), 'RTL 冻结列中的控件不可点击')
  await page.screenshot({ path: join(evidence, 'rtl-frozen-columns.png'), fullPage: true })
  await page.mouse.wheel(600, -600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top >= top - 2, rtlColumnsDelivery.y)
  await goto('Pivot!K3'); await command('View', 'freeze-panes')
  await goto('Pivot!B3'); await command('View', 'freeze-panes')
  const rtlFrozen = await bounds(), rtlDeliveryStart = await delivery.boundingBox()
  await page.mouse.move(350, 750); await page.mouse.wheel(0, 600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 550, rtlDeliveryStart.y)
  const rtlScrolled = await bounds()
  assert(Math.abs(rtlScrolled.slicer.y - rtlFrozen.slicer.y) < 2, 'RTL 冻结行控件纵向漂移')
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), 'RTL 冻结带内控件不可点击')
  await page.screenshot({ path: join(evidence, 'rtl-frozen-controls.png'), fullPage: true })
  await page.mouse.wheel(0, -600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top >= top - 2, rtlDeliveryStart.y)
  await page.locator('[data-action="save"]').click()
  await page.waitForFunction(() => document.querySelector('.save-state-label')?.textContent?.includes('已保存修订 2'), null, { timeout: 60000 })
  await page.goto(`${base}/reports/v1/native/pivot-protection/2`); await ready(); await goto('Pivot!A1'); await slicer.waitFor({ state: 'visible' })
  const reopened = await bounds()
  assert(Math.abs(separation(reopened) - separation(applied)) < 2, 'RTL 保存重开后控件锚点间距发生变化')
  const reopenedDelivery = await delivery.boundingBox()
  await page.mouse.move(350, 750); await page.mouse.wheel(0, 600)
  await page.waitForFunction(top => document.querySelector('[data-pivot-control="Timeline_P1_F4"]')?.getBoundingClientRect().top < top - 550, reopenedDelivery.y)
  assert(await slicer.locator('[type="submit"]').evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) }), '保存重开后跨冻结线控件不可点击')
  await page.screenshot({ path: join(evidence, 'rtl-reopened.png'), fullPage: true })
  return { initial, crossed, crossedScrolled, frozen, scrolled, rtl, reattached, applied, rtlColumns, rtlColumnsScrolled, rtlFrozen, rtlScrolled, reopened }
}
