import assert from 'node:assert/strict'
import { chromium, firefox, webkit } from 'playwright'

const engine = process.env.REPORT_EDITOR_BROWSER ?? 'chromium'
assert.ok(['chromium', 'firefox', 'webkit'].includes(engine), `Unsupported browser: ${engine}`)
const browser = await ({ chromium, firefox, webkit })[engine].launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  let requests = 0
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().includes('/api/')) requests += 1 })
  await page.goto(process.env.REPORT_EDITOR_URL ?? 'http://127.0.0.1:4173/reports/v1/editor/fixture-report/1', { waitUntil: 'networkidle' })
  await page.locator('[data-action="sources"]').click()
  await page.locator('.evidence-directory-item', { hasText: '收入明细.csv' }).click()
  await page.locator('.evidence-table').waitFor()
  await page.locator('.evidence-directory-item', { hasText: '正文引用' }).click()
  const title = page.locator('.evidence-object-title')
  await page.locator('.evidence-subject-links').waitFor()
  const subjectTitle = await title.textContent()
  const tabs = page.locator('.evidence-tabs .evidence-tab')
  const focused = locator => locator.evaluate(node => node === document.activeElement)
  await tabs.nth(2).focus()
  const before = requests
  await page.keyboard.press('ArrowLeft')
  assert.equal(await focused(tabs.nth(1)), true)
  assert.equal(await title.textContent(), subjectTitle)
  await page.keyboard.press('Home')
  assert.equal(await focused(tabs.nth(0)), true)
  await page.keyboard.press('Delete')
  assert.equal(await tabs.count(), 3)
  await page.keyboard.press('End')
  assert.equal(await focused(tabs.nth(2)), true)
  await page.keyboard.press('ArrowRight')
  assert.equal(await focused(tabs.nth(0)), true)
  await page.keyboard.press('ArrowRight')
  assert.equal(await focused(tabs.nth(1)), true)
  assert.equal(await title.textContent(), subjectTitle)
  assert.equal(requests, before)
  await page.keyboard.press('Space')
  await page.locator('.evidence-table').waitFor()
  assert.equal(await focused(title), true)
  await tabs.nth(2).focus()
  await page.keyboard.press('Enter')
  await page.locator('.evidence-subject-links').waitFor()
  assert.equal(await focused(title), true)
  await tabs.nth(1).focus()
  await page.keyboard.press('Delete')
  assert.equal(await tabs.count(), 2)
  assert.equal(await title.textContent(), subjectTitle)
  await page.locator('.evidence-relations-toggle').focus()
  await page.keyboard.press('Enter')
  const node = page.locator('.evidence-node').filter({ hasText: '事实 ·' })
  await node.waitFor()
  const positions = () => page.locator('.evidence-node').evaluateAll(nodes => nodes.map(node => [node.dataset.evidenceNode, node.style.left, node.style.top]))
  const initial = await positions()
  await node.focus()
  await page.keyboard.press('Space')
  await page.locator('.evidence-node.is-selected').waitFor()
  assert.equal(await title.textContent(), subjectTitle)
  assert.equal(await page.locator('[data-evidence="back"]').isEnabled(), false)
  assert.equal(await focused(node), true)
  assert.deepEqual(await positions(), initial)
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => !document.querySelector('.evidence-node.is-selected'))
  assert.equal(await focused(node), true)
  await page.keyboard.press('Space')
  await page.getByRole('button', { name: '关闭预览', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => !document.querySelector('.evidence-node.is-selected'))
  assert.equal(await focused(node), true)
  await page.keyboard.press('Enter')
  await page.locator('.evidence-fact-value').waitFor()
  assert.equal(await focused(title), true)
  assert.equal(await page.locator('[data-evidence="back"]').isEnabled(), true)
  assert.equal(await page.locator('.evidence-crumb-current[aria-current="page"]').count(), 1)
  await tabs.nth(1).focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('.evidence-shell').isVisible(), false)
  assert.equal(await page.locator('#report-editor .ProseMirror').evaluate(node => node === document.activeElement), true)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ engine, manualTabs: 'passed', homeEndDelete: 'passed', graphKeys: 'passed', previewFocus: 'passed', editorReturn: 'passed' }))
} finally {
  await browser.close()
}
