import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function runPivotControlGeometrySmoke({ page, base, ready, command, goto, draft, evidence }) {
  await page.goto(`${base}/reports/v1/native/pivot-protection/1`); await ready(); await goto('Pivot!A1')
  const slicer = page.locator('[data-pivot-control="Slicer_P1_F1"]'), timeline = page.locator('[data-pivot-control="Timeline_P1_F0"]')
  const move = slicer.locator('[data-control-geometry="move"]'), resize = slicer.locator('[data-control-geometry="resize"]')
  await slicer.waitFor({ state: 'visible' })
  const anchors = async () => (await draft()).filter(op => op.kind === 'upsertPivotControl')
  const waitAnchor = async count => {
    await page.waitForFunction(count => Object.keys(localStorage).filter(key => key.startsWith('native-editor-draft:')).some(key => (JSON.parse(localStorage.getItem(key)).operations ?? []).filter(op => op.kind === 'upsertPivotControl').length > count), count)
    await page.waitForFunction(() => !document.querySelector('#report-editor')?.inert); await slicer.waitFor({ state: 'visible' })
  }
  const drag = async (handle, dx, dy, cancel = false) => {
    const r = await handle.boundingBox(); assert(r, '几何句柄不可见')
    const x = r.x + r.width / 2, y = r.y + r.height / 2
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + dx, y + dy, { steps: 8 })
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
  }
  await command('Review', 'sheet-protect'); await page.waitForFunction(() => document.querySelector('[data-control-geometry="move"]')?.disabled === true)
  assert(await resize.isDisabled(), '受保护工作表仍可调整尺寸')
  await command('Review', 'sheet-protect'); await page.waitForFunction(() => document.querySelector('[data-control-geometry="move"]')?.disabled === false)
  const timelineCount = (await anchors()).length
  await drag(timeline.locator('[data-control-geometry="resize"]'), 20, 20); await waitAnchor(timelineCount)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 14, column: 7, width: 500, height: 180 })
  assert.equal((await anchors()).at(-1).request.kind, 'timeline')
  await command('File', 'undo'); await page.waitForFunction(() => !document.querySelector('#report-editor')?.inert)
  await goto('Pivot!A1'); await timeline.waitFor({ state: 'visible' })
  assert.equal((await anchors()).length, timelineCount, '时间线尺寸操作未独立撤销')
  await slicer.getByLabel('West', { exact: true }).check(); await timeline.getByLabel('结束日期', { exact: true }).fill('2026-01-15')
  const original = await slicer.boundingBox(), count = (await anchors()).length
  await drag(move, 88, 24, true)
  assert.equal((await anchors()).length, count, '取消手势提交了几何操作')
  const cancelled = await slicer.boundingBox()
  assert(Math.abs(original.x - cancelled.x) < 2 && Math.abs(original.y - cancelled.y) < 2, '取消后未恢复原生布局')
  await page.locator('[data-ribbon-tab="View"]').click()
  await page.locator('[data-ribbon-menu="zoom"]').selectOption('125')
  await page.waitForFunction(() => document.querySelector('[data-pivot-control="Slicer_P1_F1"]')?.getBoundingClientRect().width > 220)
  await drag(resize, 160, -100); await waitAnchor(count)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 0, column: 9, width: 320, height: 180 })
  assert(await slicer.getByLabel('West', { exact: true }).isChecked(), '调整尺寸丢失未提交成员选择')
  assert.equal(await timeline.getByLabel('结束日期', { exact: true }).inputValue(), '2026-01-15', '调整尺寸丢失未提交日期区间')
  await command('View', 'zoom-reset')
  await page.waitForFunction(() => document.querySelector('[data-pivot-control="Slicer_P1_F1"]')?.getBoundingClientRect().width < 350)
  await drag(move, 264, 96); await waitAnchor(count + 1)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 4, column: 12, width: 320, height: 180 })
  assert(await slicer.getByLabel('West', { exact: true }).isChecked(), '移动丢失未提交成员选择')
  await page.screenshot({ path: join(evidence, 'dragged-and-resized.png'), fullPage: true })
  await command('View', 'toggle-right-to-left')
  await page.waitForFunction(() => document.querySelector('.workbook-feedback')?.textContent?.includes('已切换为从右到左')); await slicer.waitFor({ state: 'visible' })
  await goto('Pivot!K3'); await command('View', 'freeze-panes'); await move.waitFor({ state: 'visible' })
  await drag(move, 176, 48); await waitAnchor(count + 2)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 6, column: 10, width: 320, height: 180 }, 'RTL 冻结视图下未按原生单元格坐标吸附')
  const history = await draft()
  await command('File', 'undo'); await page.waitForFunction(() => !document.querySelector('#report-editor')?.inert)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 4, column: 12, width: 320, height: 180 })
  await command('File', 'redo'); await page.waitForFunction(() => !document.querySelector('#report-editor')?.inert)
  assert.deepEqual(await draft(), history, '几何撤销/重做改变了其他草稿操作')
  await goto('Pivot!A1'); await move.waitFor({ state: 'visible' })
  await drag(move, -176, -48); await waitAnchor(count + 3)
  assert.deepEqual((await anchors()).at(-1).request.anchor, { row: 4, column: 12, width: 320, height: 180 })
  await page.screenshot({ path: join(evidence, 'rtl-geometry.png'), fullPage: true })
  assert(!(await draft()).some(op => op.kind === 'applyPivotLayoutExpansions'), '几何提交意外重建透视表或应用未提交筛选')
  await page.locator('[data-action="save"]').click()
  await page.waitForFunction(() => document.querySelector('.save-state-label')?.textContent?.includes('已保存修订 2'), null, { timeout: 60000 })
  await page.goto(`${base}/reports/v1/native/pivot-protection/2`); await ready(); await goto('Pivot!A1'); await slicer.waitFor({ state: 'visible' })
  assert(!(await slicer.getByLabel('West', { exact: true }).isChecked()), '未提交成员选择被几何操作写入文件')
  assert.equal(await timeline.getByLabel('结束日期', { exact: true }).inputValue(), '2026-01-31', '未提交日期筛选被几何操作写入文件')
  await command('Insert', 'slicer-open')
  const filter = page.locator('[role="dialog"][aria-label="透视表筛选"]')
  await filter.getByLabel('筛选字段', { exact: true }).selectOption('Region')
  assert.equal(await filter.getByLabel('控件左上角单元格', { exact: true }).inputValue(), 'M5')
  assert.equal(await filter.getByLabel('控件宽度（像素）', { exact: true }).inputValue(), '320')
  assert.equal(await filter.getByLabel('控件高度（像素）', { exact: true }).inputValue(), '180')
  await filter.locator('[data-action="cancel"]').click()
  await page.screenshot({ path: join(evidence, 'geometry-reopened.png'), fullPage: true })
  return { cancelled: true, timelineResizeUndone: true, zoom: 125, rtlFrozen: true, undoRedo: true, pendingFiltersPreserved: true, geometryOnly: true, finalAnchor: 'M5', width: 320, height: 180 }
}
