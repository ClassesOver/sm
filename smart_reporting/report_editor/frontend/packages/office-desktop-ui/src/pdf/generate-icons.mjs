/** Generate static SVGs from the pinned upstream components. React/server is build-time only.
 * Run from any directory: node packages/office-desktop-ui/src/pdf/generate-icons.mjs [--check]
 */
import { build } from 'esbuild'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const directory = dirname(fileURLToPath(import.meta.url))
const temporary = await mkdtemp(join(directory, '.generate-icons-'))
try {
  const bundle = join(temporary, 'render.mjs')
  await build({
    stdin: {
      contents: `
        import { createElement } from 'react';
        import { renderToStaticMarkup } from 'react-dom/server';
        import * as Icons from './vendor/icons.tsx';
        import { GensparkMark } from './brand-mark.tsx';
        const icons = Object.fromEntries(Object.entries(Icons)
          .filter(([name]) => name.startsWith('Icon') && name !== 'Icon' && name !== 'IconRatio')
          .map(([name, component]) => [name, renderToStaticMarkup(createElement(component))]));
        export default { ...icons, GensparkMark26: renderToStaticMarkup(createElement(GensparkMark, { size: 26 })) };
      `,
      resolveDir: directory,
      sourcefile: 'generate-icons-entry.ts',
      loader: 'ts',
    },
    outfile: bundle,
    bundle: true,
    platform: 'node',
    format: 'esm',
    packages: 'external',
    jsx: 'automatic',
    logLevel: 'silent',
  })
  const { default: icons } = await import(pathToFileURL(bundle).href)
  const generated = '// Generated by generate-icons.mjs from pinned upstream SVG components. Do not edit.\n'
    + '// Apache-2.0; upstream sources, hashes, and license are in ./vendor/.\n'
    + `export const pdfDesktopIconMarkup: Readonly<Record<string, string>> = ${JSON.stringify(icons, null, 2)}\n`
  const output = join(directory, 'icons.generated.ts')
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== generated) throw new Error('PDF generated icons differ; run generate-icons.mjs')
    process.stdout.write('PDF static SVGs match the pinned source components.\n')
  } else {
    await writeFile(output, generated)
    process.stdout.write(`Generated ${Object.keys(icons).length} PDF SVGs.\n`)
  }
} finally {
  await rm(temporary, { recursive: true, force: true })
}
