type Props = NonNullable<SectionSettings['pageBorderProps']>
const names = ['top', 'left', 'bottom', 'right']
const object = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value)
const keys = (value: Record<string, unknown>, allowed: string[]) => Object.keys(value).every(key => allowed.includes(key))
const number = (value: unknown, min: number, max: number) => typeof value === 'number' && Number.isFinite(value) && value >= min && value <= max
const color = (value: unknown) => value === undefined || typeof value === 'string' && /^[0-9A-Fa-f]{6}$/.test(value)

/** Shared source-UI validation for saved page border properties and clear intents. */
export function validateDocxPageBorderProps(value: unknown, allowNull = false): value is Props | null {
  if (allowNull && value === null) return true
  if (!object(value) || !keys(value, ['display', 'offsetFrom', 'zOrder', 'spacePt', 'widthPt', 'color', 'sides'])) return false
  if (value.display !== undefined && !['firstPage', 'notFirstPage'].includes(value.display as string)
    || value.offsetFrom !== undefined && !['page', 'text'].includes(value.offsetFrom as string)
    || value.zOrder !== undefined && value.zOrder !== 'back' || !color(value.color)
    || !number(value.spacePt, 0, 31) || !Number.isInteger(value.spacePt) || !number(value.widthPt, 0.125, 31)) return false
  if (!object(value.sides) || !keys(value.sides, names) || !Object.keys(value.sides).length) return false
  for (const side of Object.values(value.sides)) {
    if (!object(side) || !keys(side, ['val', 'widthPt', 'spacePt', 'color', 'art', 'shadow', 'frame'])
      || !color(side.color) || !number(side.spacePt, 0, 31) || !Number.isInteger(side.spacePt)
      || [side.art, side.shadow, side.frame].some(flag => flag !== undefined && flag !== true)) return false
    if (side.art) {
      if (!PAGE_BORDER_ART_NAMES.includes(side.val as string) || !number(side.widthPt, 1, 31) || !Number.isInteger(side.widthPt)) return false
    } else if (!PAGE_BORDER_LINE_STYLES.includes(side.val as string)
      || !number(side.widthPt, 0.125, 12) || !Number.isInteger((side.widthPt as number) * 8)) return false
  }
  return true
}

/** Only known source controls reach the engine XML writer; source drafts retain section identities. */
export function assertDocxPageBorderProps(value: unknown): asserts value is Props {
  if (!validateDocxPageBorderProps(value)) throw new Error('section_page_border_props_invalid')
}
